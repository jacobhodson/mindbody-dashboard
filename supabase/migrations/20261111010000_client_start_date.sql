-- clients.start_date: when someone actually started with Newstrength.
-- Mindbody's creation_date is the 6 Aug 2025 import day for everyone who
-- came across from the old system, so anniversaries read start_date first
-- and fall back to creation_date (new clients just leave it blank).
-- Ours, not Mindbody's: the roster sync never writes it.

alter table clients add column start_date date;

-- Any signed-in staff can set it, same as the other one-column client RPCs
-- (20260930000020_coach_client_field_rpcs.sql).
create function set_client_start_date(p_client_id uuid, p_start date default null)
returns void
language plpgsql
security definer set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;
  update clients set start_date = p_start, updated_at = now() where id = p_client_id;
end;
$$;

revoke all on function set_client_start_date(uuid, date) from public;
grant execute on function set_client_start_date(uuid, date) to authenticated;

